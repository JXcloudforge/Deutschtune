import pytest

flask = pytest.importorskip("flask")

from api.service import create_app
from scripts.openai_compatible import InferenceHTTPError, InferenceTimeout


CONFIG = {
    "served_model_name": "legacy-model",
    "system_prompt": "legacy correction prompt must not reach Tatoeba",
    "temperature": 0,
    "top_p": 1,
    "max_tokens": 100,
    "require_tutor_gate": True,
    "tatoeba": {
        "model_name": "tatoeba-lora",
        "temperature": 0.0,
        "top_p": 1.0,
        "max_tokens": 128,
    },
}


class RecordingClient:
    def __init__(self, answer="response generated by the configured client", error=None):
        self.answer = answer
        self.error = error
        self.calls = []

    def chat_completion(self, payload, *, request_id=None):
        self.calls.append((payload, request_id))
        if self.error:
            raise self.error
        return self.answer


def test_tatoeba_restore_forwards_to_existing_client_and_returns_actual_client_text():
    client = RecordingClient(answer="client-generated word")
    response = create_app(CONFIG, client).test_client().post(
        "/tatoeba/restore",
        json={"request_id": "g7-test-001", "text": "补全德语句子：Ich ____ Wasser. 只输出缺失的词。"},
    )

    assert response.status_code == 200
    assert response.json == {
        "request_id": "g7-test-001",
        "model": "tatoeba-lora",
        "response": "client-generated word",
    }
    assert len(client.calls) == 1
    payload, request_id = client.calls[0]
    assert request_id == "g7-test-001"
    assert payload["model"] == "tatoeba-lora"
    assert payload["messages"] == [{
        "role": "user",
        "content": "补全德语句子：Ich ____ Wasser. 只输出缺失的词。",
    }]
    assert payload["stream"] is False


@pytest.mark.parametrize(
    ("request_body", "status"),
    [
        ({"request_id": "g7-empty", "text": "  "}, 400),
        ({"text": "Ich ____ Wasser."}, 400),
        ({"request_id": "bad id", "text": "Ich ____ Wasser."}, 400),
    ],
)
def test_tatoeba_restore_rejects_invalid_input_without_upstream_call(request_body, status):
    client = RecordingClient()
    response = create_app(CONFIG, client).test_client().post("/tatoeba/restore", json=request_body)
    assert response.status_code == status
    assert client.calls == []


@pytest.mark.parametrize(
    ("error", "status"),
    [(InferenceTimeout("timeout"), 504), (InferenceHTTPError("connection failed"), 502)],
)
def test_tatoeba_restore_maps_upstream_failures(error, status):
    client = RecordingClient(error=error)
    response = create_app(CONFIG, client).test_client().post(
        "/tatoeba/restore", json={"request_id": "g7-error", "text": "Ich ____ Wasser."}
    )
    assert response.status_code == status
    assert response.json["request_id"] == "g7-error"
    assert len(client.calls) == 1


def test_tatoeba_route_does_not_disable_chat_gate_or_change_health():
    client = RecordingClient()
    app_client = create_app(CONFIG, client).test_client()
    chat = app_client.post("/chat", json={"request_id": "g7-chat", "text": "Hallo"})
    health = app_client.get("/healthz")

    assert chat.status_code == 409
    assert chat.json["error"] == "UNSTRUCTURED_CHAT_DISABLED_QUALITY_GATE_REQUIRED"
    assert health.status_code == 200
    assert health.json == {"status": "ok"}
    assert client.calls == []


def test_tatoeba_route_rejects_oversized_body_without_upstream_call():
    client = RecordingClient()
    config = {**CONFIG, "max_request_bytes": 32}
    response = create_app(config, client).test_client().post(
        "/tatoeba/restore",
        data='{"request_id":"too-large","text":"' + ("x" * 100) + '"}',
        content_type="application/json",
    )

    assert response.status_code == 413
    assert response.json == {"error": "REQUEST_TOO_LARGE"}
    assert client.calls == []


@pytest.mark.parametrize("limit", [0, -1, 1048577, True, "1024"])
def test_create_app_rejects_invalid_request_size_limit(limit):
    with pytest.raises(ValueError, match="max_request_bytes"):
        create_app({**CONFIG, "max_request_bytes": limit}, RecordingClient())
